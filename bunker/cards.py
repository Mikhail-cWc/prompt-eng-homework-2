def deal_cards(seed: str) -> list[dict[str, str]]:
    rng = random.Random(f"{CATALOG_VERSION}:{seed}")
    columns = {key: rng.sample(CATALOG[key], 6) for key in TRAITS}
    return [{key: columns[key][slot] for key in TRAITS} for slot in range(6)]
